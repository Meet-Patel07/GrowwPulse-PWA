// Helper to generate realistic historical candle series
function generateCandles(basePrice: number, count: number, volatility: number, trend: number): CandleData[] {
  const candles: CandleData[] = [];
  let currentClose = basePrice;
  const now = Date.now();
  const stepMs = 60000 * 5; // 5-minute intervals for intraday base

  for (let i = count; i >= 0; i--) {
    const time = new Date(now - i * stepMs).toLocaleTimeString([], { hour: '2-digit', minute: '2-digit' });
    const change = (Math.random() - 0.48 + trend) * volatility * currentClose;
    const open = currentClose;
    const close = Math.max(1, open + change);
    const high = Math.max(open, close) + Math.random() * volatility * currentClose * 0.5;
    const low = Math.min(open, close) - Math.random() * volatility * currentClose * 0.5;
    const volume = Math.floor(Math.random() * 50000 + 10000);

    candles.push({
      time,
      timestamp: now - i * stepMs,
      open: Number(open.toFixed(2)),
      high: Number(high.toFixed(2)),
      low: Number(low.toFixed(2)),
      close: Number(close.toFixed(2)),
      volume,
    });
    currentClose = close;
  }
  return candles;
}

function generateTimeframeCandles(basePrice: number): { [key in TimeFrame]: CandleData[] } {
  return {
    '1D': generateCandles(basePrice, 75, 0.003, 0.0002),
    '1W': generateCandles(basePrice * 0.98, 80, 0.008, 0.0004),
    '1M': generateCandles(basePrice * 0.94, 90, 0.015, 0.0006),
    '1Y': generateCandles(basePrice * 0.85, 100, 0.025, 0.0008),
    '5Y': generateCandles(basePrice * 0.45, 120, 0.04, 0.0012),
    'ALL': generateCandles(basePrice * 0.25, 140, 0.05, 0.0015),
  };
}

function generateDepth(currentPrice: number): MarketDepth {
  const bids = [
    { price: Number((currentPrice - 0.20).toFixed(2)), orders: 42, quantity: 4500 },
    { price: Number((currentPrice - 0.45).toFixed(2)), orders: 28, quantity: 3200 },
    { price: Number((currentPrice - 0.75).toFixed(2)), orders: 65, quantity: 8900 },
    { price: Number((currentPrice - 1.10).toFixed(2)), orders: 19, quantity: 1400 },
    { price: Number((currentPrice - 1.50).toFixed(2)), orders: 54, quantity: 7200 },
  ];
  const asks = [
    { price: Number((currentPrice + 0.20).toFixed(2)), orders: 35, quantity: 3800 },
    { price: Number((currentPrice + 0.50).toFixed(2)), orders: 41, quantity: 5100 },
    { price: Number((currentPrice + 0.80).toFixed(2)), orders: 18, quantity: 2300 },
    { price: Number((currentPrice + 1.25).toFixed(2)), orders: 72, quantity: 9600 },
    { price: Number((currentPrice + 1.60).toFixed(2)), orders: 23, quantity: 2900 },
  ];

  const buyTotal = bids.reduce((acc, curr) => acc + curr.quantity, 0);
  const sellTotal = asks.reduce((acc, curr) => acc + curr.quantity, 0);
  const total = buyTotal + sellTotal;

  return {
    buyTotal,
    sellTotal,
    buyPercentage: Math.round((buyTotal / total) * 100),
    sellPercentage: Math.round((sellTotal / total) * 100),
    bids,
    asks,
  };
}

